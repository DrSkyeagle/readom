"""Writes epdc/tests/png_fixtures.h: the pictures png_test.cpp decodes.

The pictures are made here rather than committed as binary files so that what
each one is meant to contain is written down next to it, and so that the test
can check exact pixels: a fixture is a 2x2 picture of four known colours, not
an image somebody once chose.

    python3 device/amazon/pw3/epdc/tests/make-png-fixtures.py

Pillow writes the 8-bit ones (RGBA, grey, palette with a transparent entry);
the 16-bit one has no Pillow mode that round-trips, so it is written chunk by
chunk. The two oversized ones are the 2x2 RGBA picture with only its IHDR
dimensions changed -- what a decoder has to refuse before it allocates a
picture this device cannot hold.
"""
import io
import os
import struct
import zlib

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))


def chunk(tag, payload):
    return struct.pack('>I', len(payload)) + tag + payload + struct.pack('>I', zlib.crc32(tag + payload) & 0xFFFFFFFF)


def raw_png(width, height, bit_depth, colour_type, rows, interlace=0):
    """A PNG whose rows are given raw (each with filter 0 in front)."""
    ihdr = struct.pack('>IIBBBBB', width, height, bit_depth, colour_type, 0, 0, interlace)
    raw = b''.join(b'\x00' + row for row in rows)
    return b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', ihdr) + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b'')


def saved(image, **kwargs):
    out = io.BytesIO()
    image.save(out, format='PNG', **kwargs)
    return out.getvalue()


def with_dimensions(png, width, height):
    """The same PNG with only the dimensions in its IHDR replaced."""
    assert png[12:16] == b'IHDR'
    ihdr = bytearray(png[16:29])
    struct.pack_into('>II', ihdr, 0, width, height)
    fixed = bytes(ihdr)
    return png[:16] + fixed + struct.pack('>I', zlib.crc32(b'IHDR' + fixed) & 0xFFFFFFFF) + png[29:]


def emit(name, data, f):
    f.write('static const unsigned char %s[] = {\n' % name)
    for i in range(0, len(data), 12):
        f.write('    ' + ', '.join('0x%02x' % byte for byte in data[i:i + 12]) + ',\n')
    f.write('};\n')
    f.write('static const unsigned long %sSize = %d;\n\n' % (name, len(data)))


def main():
    rgba2x2 = Image.new('RGBA', (2, 2))
    rgba2x2.putdata([(255, 0, 0, 255), (0, 255, 0, 128), (0, 0, 255, 0), (255, 255, 255, 64)])

    gray4x2 = Image.new('L', (4, 2))
    gray4x2.putdata([0, 85, 170, 255, 255, 170, 85, 0])

    palette = Image.new('P', (2, 2))
    palette.putpalette([10, 20, 30, 200, 100, 50, 0, 255, 0, 255, 255, 255])
    palette.putdata([0, 1, 2, 3])
    palette.info['transparency'] = bytes([0, 64, 128, 255])

    solid1x1 = Image.new('RGB', (1, 1), (100, 150, 200))

    fixtures = {
        'kRgba2x2': saved(rgba2x2),
        'kGray4x2': saved(gray4x2),
        'kPalette2x2': saved(palette, transparency=bytes([0, 64, 128, 255])),
        'kSolid1x1': saved(solid1x1),
        'kRgb16x1': raw_png(1, 1, 16, 2, [struct.pack('>HHH', 0x1234, 0x5678, 0x9ABC)]),
    }
    fixtures['kOversizedSide'] = with_dimensions(fixtures['kRgba2x2'], 8000, 2)
    fixtures['kOversizedPixels'] = with_dimensions(fixtures['kRgba2x2'], 4000, 4000)

    text = io.StringIO()
    text.write('// SPDX-License-Identifier: Apache-2.0\n')
    text.write('// Generated by make-png-fixtures.py -- do not edit; change the script and run it.\n')
    text.write('// What each picture holds is in the script, next to the picture.\n')
    text.write('#pragma once\n\n')
    for name, data in fixtures.items():
        emit(name, data, text)
    body = text.getvalue().rstrip('\n') + '\n'
    with open(os.path.join(HERE, 'png_fixtures.h'), 'w', newline='\n') as f:
        f.write(body)
    print('wrote png_fixtures.h (%d fixtures)' % len(fixtures))


if __name__ == '__main__':
    main()
