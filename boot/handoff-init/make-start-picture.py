"""The picture the handover's init draws once it has the display driver
(pw3-handoff-init.c), generated from the installer's own "正在启动 Android"
screen so that one screen stands from the tap to Android's first frame.

Why it has to be drawn again at all: the kernel that takes over allocates its
own framebuffer, and dma_alloc_writecombine() returns it zeroed
(arch/arm/mm/dma-mapping.c, __dma_alloc_buffer -> memset). mxc_epdc_fb_probe()
then calls do_epdc_init_sequence() unconditionally, which clears the panel with
the INIT waveform and submits one full update of that zeroed buffer. Whatever
the installer left on the screen is gone by the time anything of ours runs, and
without this the panel stands dark until Android's first frame.

The region is the installer's text block for its BOOT screen, laid out by
installer/screens/render_screens.py with the same fonts, then quantised to the
panel's sixteen grey levels -- which is all a GC16 update can show -- and run
length encoded. It is a committed header rather than a file in the initramfs
because every entry needs it, test entries included, while the installer's
screens.bin is a release artefact: the handover must not depend on a release
payload having been built.

Needs Pillow and the fonts, which are in the build VM, where the port is
mounted read only: --write takes an --output directory for that reason, and the
file is copied into the tree from the host (the same way the sleep pictures are
made, device/amazon/pw3/sleep/README.md). --check needs no write and is the
one a test runs.

Usage: make-start-picture.py (--write [--output DIR] | --check) [--preview PNG]
                             --cjk-font NotoSansCJK-Regular.ttc
                             --latin-font Roboto-Regular.ttf
                             --latin-title-font Roboto-Medium.ttf
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / 'installer/screens'))
import render_screens as rs                                   # noqa: E402
from PIL import Image                                         # noqa: E402

HEADER = HERE / 'start-picture.h'
# The panel shows sixteen levels (0, 17, ... 255): quantising here rather than
# leaving it to the EPDC is what makes the encoding short, and changes nothing
# that reaches the eye.
LEVELS = 17


def quantised(image):
    return bytes((value + LEVELS // 2) // LEVELS * LEVELS for value in image.tobytes())


def runs(pixels):
    """(grey, how many) pairs, row after row. A run is at most 255 pixels."""
    out = bytearray()
    at = 0
    while at < len(pixels):
        grey = pixels[at]
        length = 1
        while length < 255 and at + length < len(pixels) and pixels[at + length] == grey:
            length += 1
        out += bytes((grey, length))
        at += length
    # Decoded here the way the C decoder decodes it, and compared with what
    # went in: the picture ships as these bytes and nothing else reads them
    # until the device does.
    back = bytearray()
    for grey, length in zip(out[0::2], out[1::2]):
        back += bytes((grey,)) * length
    if bytes(back) != pixels:
        raise SystemExit('the runs do not decode back to the picture (%d pixels against %d)'
                         % (len(back), len(pixels)))
    return bytes(out)


def picture(a):
    """The BOOT screen's text block as the installer lays it out."""
    fonts = rs.Fonts(a.cjk_font, a.latin_font, a.latin_title_font)
    return rs.text_block(fonts, rs.BOOT_ZH, rs.BOOT_EN, rs.BOOT_BODY)


def header(image, encoded):
    body = ['/* Generated by boot/handoff-init/make-start-picture.py; do not edit. */',
            '#pragma once', '#include <stdint.h>', '',
            '/* "%s" / "%s", as installer/screens/render_screens.py lays it out,'
            % (rs.BOOT_ZH, rs.BOOT_EN),
            ' * rasterised by Pillow %s. The version is here because the raster'
            % Image.__version__,
            ' * depends on it: another Pillow lays the same words out to a',
            ' * different height, and --check is then telling you which it is. */',
            '#define PW3_START_W %d' % image.width,
            '#define PW3_START_H %d' % image.height,
            '#define PW3_START_PIXELS %du' % (image.width * image.height),
            '/* Where the block sits on the panel it was laid out for. The installer puts',
            ' * it below the stock status bar and across the width; both are kept as the',
            ' * panel\'s own proportions, so a panel of another size places it the same way',
            ' * instead of needing a second layout. */',
            '#define PW3_START_PANEL_W %d' % rs.SCREEN_W,
            '#define PW3_START_PANEL_H %d' % rs.SCREEN_H,
            '#define PW3_START_TOP %d' % rs.REGION_Y,
            '',
            '/* (grey, how many pixels), row after row: %d levels, %d runs. */'
            % (len(set(encoded[0::2])), len(encoded) // 2),
            'static const uint8_t pw3_start_runs[] = {']
    for at in range(0, len(encoded), 16):
        body.append('\t' + ' '.join('%d,' % byte for byte in encoded[at:at + 16]))
    return '\n'.join(body + ['};', ''])


def preview(image, path):
    """The panel as the reader would see it, for review."""
    screen = Image.new('L', (rs.SCREEN_W, rs.SCREEN_H), 255)
    left = (rs.SCREEN_W - image.width) // 2
    screen.paste(image, (left, rs.REGION_Y))
    screen.save(path, optimize=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    what = ap.add_mutually_exclusive_group(required=True)
    what.add_argument('--write', action='store_true', help='write %s' % HEADER.name)
    what.add_argument('--check', action='store_true', help='compare it with what the fonts give now')
    ap.add_argument('--output', type=Path, default=HERE, help='where --write puts it (default: beside this script)')
    ap.add_argument('--preview', type=Path)
    for name in ['cjk-font', 'latin-font', 'latin-title-font']:
        ap.add_argument('--' + name, type=Path, required=True)
    a = ap.parse_args()
    image = picture(a)
    encoded = runs(quantised(image))
    text = header(image, encoded)
    if a.preview:
        preview(image, a.preview)
    if a.check:
        if not HEADER.exists():
            raise SystemExit('%s is missing; run --write' % HEADER)
        if HEADER.read_text() != text:
            was = re.search(r'rasterised by Pillow (\S+)', HEADER.read_text())
            raise SystemExit('%s is not what these fonts and this layout give; run --write.'
                             ' This is Pillow %s and the file was written with Pillow %s.'
                             % (HEADER, Image.__version__, was.group(1) if was else 'unrecorded'))
        print('%s: %d x %d, %d runs, up to date' % (HEADER.name, image.width, image.height,
                                                    len(encoded) // 2))
        return
    written = a.output / HEADER.name
    written.write_text(text)
    print('%s: %d x %d, %d runs, %d bytes of runs' % (written, image.width, image.height,
                                                      len(encoded) // 2, len(encoded)))


if __name__ == '__main__':
    main()
