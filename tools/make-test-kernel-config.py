"""Assemble the configuration of one QEMU test kernel from the port's own files.

There are two test kernels, both vexpress-a9 and neither a Kindle:

  * `smoke` -- one Linux, a diskless initramfs, the kernel interface suite
    (tools/build-kernel-smoke.sh);
  * `loader-stage` -- the first Linux of the handoff, which loads boot/handoff
    as a module and jumps to a second Linux
    (tools/build-loader-stage-kernel.sh, boot/profiles/qemu-vexpress.json).

Both answer the same question as `config/android-core.config` -- what this port
needs of a kernel -- so that is the base, with the device's own drivers taken
out: a VExpress board has no MAX77696, no Cypress touch controller, no i.MX USB
gadget, and nothing for an identifier policy to protect. What is left is the
port, which is the thing under test.

This existed as a heredoc inside tools/build-kernel-smoke.sh, where three lists
were appended to each other and whichever came last won. Six options were asked
for twice with the same value, and `CONFIG_NETDEVICES` was asked for twice with
different values: the override said the test kernel had no network devices and
the network suite's own list, appended after it, said it had. The kernel had
them. Nothing reported the contradiction, and the reason for the value was in
the file that lost.

So an option may still be declared by more than one of these files, because a
suite's list of requirements is a statement of what it needs rather than a
declaration site -- but the result is one value, the last declaration wins, and
every override is printed and written into the output beside the value it
replaced. An override that nobody meant is then a line in the build log and a
failure in tools/tests/test_kconfig_fragments.py, which pins the set.

Usage: make-test-kernel-config.py --profile smoke|loader-stage --output FILE
"""
import argparse
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Everything the device has and a vexpress-a9 does not. Keeping the names out
# rather than setting them to `n` leaves Kconfig free to answer for the board
# it was given, which is the whole point of building for another machine.
HARDWARE = re.compile(r'CONFIG_(USB_|LAB126_|WARIO_|CYPRESS_|TOUCHSCREEN_|RTC_DRV_MAX77696)')

BASE = 'config/android-core.config'
SHARED = 'config/test-kernel/vexpress.config'
# The network interface suite states its own requirements, and its README asks
# whoever integrates it to enable CONFIG_NETDEVICES here rather than there.
NETWORK = 'tools/kernel-smoke/network/required.config'
PROFILES = {'smoke': 'config/test-kernel/smoke.config',
            'loader-stage': 'config/test-kernel/loader-stage.config'}


def setting_reader():
    """The one definition of what a configuration line is: merge-kconfig.py's."""
    path = ROOT / 'tools/merge-kconfig.py'
    spec = importlib.util.spec_from_file_location('pw3_merge_kconfig', path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.setting


def assemble(profile):
    setting = setting_reader()
    sources = [BASE, SHARED, NETWORK, PROFILES[profile]]
    chosen = {}
    origin = {}
    replaced = {}
    agreed = 0
    for name in sources:
        for line in (ROOT / name).read_text().splitlines():
            found = setting(line)
            if not found:
                continue
            key, value = found
            if name == BASE and HARDWARE.search(key):
                continue
            if key in chosen:
                if chosen[key] == value:
                    agreed += 1
                    continue
                replaced[key] = (chosen[key], origin[key], name)
            chosen[key] = value
            origin.setdefault(key, name)
    return chosen, origin, replaced, agreed


def render(profile, chosen, origin, replaced):
    out = ['# Generated by tools/make-test-kernel-config.py --profile %s' % profile,
           '# Do not edit: edit %s, %s, %s or %s.'
           % (BASE, SHARED, NETWORK, PROFILES[profile]), '#',
           '# A QEMU vexpress-a9 test kernel. Not a Kindle kernel and not a flash recipe.']
    for key, value in chosen.items():
        if key in replaced:
            was, first, last = replaced[key]
            out.append('# %s said %s; %s asks for %s, which is what this is.'
                       % (first, was, last, value))
        out.append('# %s is not set' % key if value == 'n' else '%s=%s' % (key, value))
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--profile', required=True, choices=sorted(PROFILES))
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    chosen, origin, replaced, agreed = assemble(args.profile)
    text = render(args.profile, chosen, origin, replaced)
    args.output.write_text(text)
    for key, (was, first, last) in sorted(replaced.items()):
        print('%s: %s asked for %s, %s for %s -- %s applies'
              % (key, first, was, last, chosen[key], last), file=sys.stderr)
    print('%s: %d options, %d of them asked for twice with the same value, %d overridden'
          % (args.profile, len(chosen), agreed, len(replaced)))


if __name__ == '__main__':
    main()
