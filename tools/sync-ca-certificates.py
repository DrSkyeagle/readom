#!/usr/bin/env python3
"""Write the patch that gives Android 8.1's system/ca-certificates the current Android root set.

Android 8.1 (r81) carries the trusted roots of 2017: 135 files, among them roots
distrusted since (Symantec's VeriSign, GeoTrust and thawte, TURKTRUST, E-Tugra,
Certinomis) and none of the roots issued since (GTS R1-R4, ISRG Root X2,
Microsoft 2017, Sectigo R46/E46, DigiCert G5, ...). The roots are data read at
run time (Conscrypt's TrustedCertificateStore reads /system/etc/security/cacerts;
the file name is the certificate's OpenSSL subject_hash_old, as in every later
Android), so the current list replaces the old one file for file.

UPSTREAM_COMMIT is the newest public update of that list ("Update certificates to
NSS_3_112_RTM", android16-qpr2-release). FILES_MANIFEST_SHA256 pins its content:
the SHA-256 of the lines "<name> <sha256 of file>\\n" in name order, so the check
does not depend on how Gitiles packs the archive.

Usage: sync-ca-certificates.py PROJECT_DIR OUTPUT_PATCH [--archive FILES_TAR_GZ]
  PROJECT_DIR: an unpatched checkout of system/ca-certificates (android-8.1.0_r81)
  --archive:   the files.tar.gz of UPSTREAM_COMMIT, when already downloaded
"""
import argparse
import hashlib
import io
import re
import shutil
import subprocess
import tarfile
import tempfile
import urllib.request
from pathlib import Path

UPSTREAM = 'https://android.googlesource.com/platform/system/ca-certificates'
UPSTREAM_COMMIT = 'c5434e0a849069a428da76c71b3c13f400b5f8cf'
FILES_MANIFEST_SHA256 = 'eaae34b2e338657182f10c9399eb54ab89070905d4def0185995f8b2a6656ec7'
NAME = re.compile(r'^[0-9a-f]{8}\.[0-9]$')

HEADER = """From: PW3 Android port
Subject: [PW3] ca-certificates: the Android root set of {commit}

Android 8.1 trusts the roots of 2017: {old} files, among them roots
distrusted since and none of those issued since. This is the list Android
ships today, the newest public update of system/ca-certificates
({commit}, "Update certificates to NSS_3_112_RTM",
android16-qpr2-release): {new} roots, {added} added, {removed} removed,
{changed} replaced under the same name. Generated by
tools/sync-ca-certificates.py, which pins that commit and the content.

The file names are the OpenSSL subject_hash_old of each certificate, which
is what Conscrypt's TrustedCertificateStore in 8.1 looks up; every new name
was checked against its certificate. Chains of 31 sites often visited from
the device (WeRead, Baidu, Zhihu, Bilibili, GitHub, Google, Microsoft,
Wikipedia, Let's Encrypt, MobileRead, ...) verify with the old set and with
this one (OpenSSL, 2026-10-16).
---
"""


def manifest_sha256(files):
    lines = ''.join('%s %s\n' % (n, hashlib.sha256(files[n]).hexdigest()) for n in sorted(files))
    return hashlib.sha256(lines.encode()).hexdigest()


def read_archive(data):
    files = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as tar:
        for member in tar.getmembers():
            name = member.name.lstrip('./')
            if not member.isfile() or not NAME.match(name):
                raise SystemExit('unexpected archive member: %r' % member.name)
            files[name] = tar.extractfile(member).read()
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('project', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--archive', type=Path)
    args = parser.parse_args()
    data = args.archive.read_bytes() if args.archive else urllib.request.urlopen(
        '%s/+archive/%s/files.tar.gz' % (UPSTREAM, UPSTREAM_COMMIT), timeout=120).read()
    new = read_archive(data)
    digest = manifest_sha256(new)
    if digest != FILES_MANIFEST_SHA256:
        raise SystemExit('content of %s does not match the pin: %s' % (UPSTREAM_COMMIT, digest))
    for name, body in new.items():
        pem = re.search(rb'-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----', body, re.S)
        got = subprocess.run(['openssl', 'x509', '-noout', '-subject_hash_old'], input=pem.group(0),
                             capture_output=True, check=True).stdout.decode().strip()
        if got != name.split('.')[0]:
            raise SystemExit('%s: subject_hash_old is %s' % (name, got))
    old_dir = args.project / 'files'
    old = {p.name: p.read_bytes() for p in old_dir.iterdir() if p.is_file()}
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp) / 'ca-certificates'
        shutil.copytree(args.project, work, ignore=shutil.ignore_patterns('.git', '.pw3-applied-patches.json'))
        git = ['git', '-C', str(work), '-c', 'user.name=pw3', '-c', 'user.email=pw3@localhost']
        subprocess.run(git + ['init', '-q'], check=True)
        subprocess.run(git + ['add', '-A'], check=True)
        subprocess.run(git + ['commit', '-q', '-m', 'base'], check=True)
        shutil.rmtree(work / 'files')
        (work / 'files').mkdir()
        for name, body in new.items():
            (work / 'files' / name).write_bytes(body)
        subprocess.run(git + ['add', '-A'], check=True)
        diff = subprocess.run(git + ['diff', '--cached', '--no-color', '--no-renames'],
                              capture_output=True, check=True).stdout.decode()
    added = len(set(new) - set(old))
    removed = len(set(old) - set(new))
    changed = sum(1 for n in set(new) & set(old) if new[n] != old[n])
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(HEADER.format(commit=UPSTREAM_COMMIT[:12], old=len(old), new=len(new),
                                         added=added, removed=removed, changed=changed) + diff)
    print('%d -> %d roots: %d added, %d removed, %d replaced; %s' % (len(old), len(new), added, removed,
                                                                     changed, args.output))


if __name__ == '__main__':
    main()
