"""The storage entry (`pw3-testfile-init`, PID 1 after the boot-only jump), built outside AOSP.

The entry is one C file with headers (`device/amazon/pw3/preinit/PreInit.c` plus
the headers it includes) and three things from the build: a libc, a SHA-256, and
the board name the kernel release is checked against. Inside AOSP the module in
`device/amazon/pw3/preinit/Android.mk` takes clang, bionic and BoringSSL's
libcrypto; this script takes the static musl toolchain, `tools/preinit-sha256.c`
(project-owned, Apache-2.0) and `-DPW3_BOARD_NAME`, so a Voyage entry can be
produced with no AOSP tree at all (the port's gap G1).

The kernel headers come from the cross toolchain's arm sysroot, and are added
with `-idirafter` rather than `-isystem`: the musl headers have to win every
lookup they can answer, or glibc's `stdint.h`/`stdio.h` get mixed into the
compile. Only `linux/` and `asm*/` are wanted from there.

What this proves before it calls the build good:
  * the SHA-256 passes the NIST known-answer vectors, compiled and run on the
    host (a wrong digest in PID 1 would be reported as a damaged image);
  * `release_is_this_board()` accepts this board's kernel release and refuses
    the other model's, compiled and run on the host from the untouched
    PreInit.c (the function is `static`, so the test is one translation unit
    with main renamed -- see host_board_gate());
  * the output is a static ARM EABI5 executable with no interpreter, whose entry
    point is inside an executable segment;
  * the binary carries the program's contract string and a board gate that
    names this board.

Usage: build-preinit.py --output DIR [--board BOARD ...]
  --output  directory the binaries and a facts JSON are written to
  --board   a board name to build for; repeatable; default: voyage. pw3 builds
            the control whose only difference is -DPW3_BOARD_NAME.

Run as builder in the build VM (hostname READOM_BUILD_HOST, default lima-pw3), the same rule as every other
build script in this tree. The musl toolchain is the one tools/build-test-libc.sh
installs.
"""
import argparse
import hashlib
import json
import os
import platform
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PREINIT = REPO / 'device/amazon/pw3/preinit'
SHA_SOURCE = REPO / 'tools/preinit-sha256.c'
DEFAULT_MUSL = Path('/home/builder/toolchains/musl-arm/bin/musl-gcc')
DEFAULT_KERNEL_HEADERS = Path('/usr/arm-linux-gnueabi/include')
CONTRACT = ('PW3_TESTFILE_INIT_V12_DM_CLUSTER_EXTENTS_FAT_READONLY_VERIFY_THEN_RW_ANDROID_TMPFS_COVERED'
            '_KINDLE_ROOT_VIEW_READ_ONLY_DATA_SIZED_IMAGES_SYSTEM_STAMP_BACKGROUND_RECHECK'
            '_FAT_CROSSLINK_OPTIONAL_REPORT_AREA_IMAGE_OWNS_APP_CODE_THREE_KEY_CMDLINE_NO_PARTITIONING')

# The <openssl/sha.h> PreInit.c compiles against in this build. It is the same
# interface the AOSP module gets from BoringSSL, narrowed to the four names the
# entry uses and satisfied by tools/preinit-sha256.c. Written into the output
# directory so the compile is self-contained (there is no system OpenSSL for
# arm-linux-musleabi). SHA256_CTX's fields are the ones preinit-sha256.c names.
SHA_HEADER = '''\
/* Generated by tools/build-preinit.py; not a system file.
 *
 * The subset of <openssl/sha.h> that the storage entry uses, implemented by
 * tools/preinit-sha256.c (Apache-2.0). Inside AOSP the same interface comes
 * from BoringSSL's libcrypto.
 */
#ifndef PW3_PREINIT_OPENSSL_SHA_H
#define PW3_PREINIT_OPENSSL_SHA_H
#include <stddef.h>
#include <stdint.h>

#define SHA256_DIGEST_LENGTH 32

typedef struct {
    uint32_t h[8];          /* state: h0..h7 */
    uint64_t bits;          /* bytes fed so far, times 8, as the length field needs it */
    unsigned char block[64];/* the partial block still to be compressed */
    size_t used;            /* bytes used in block */
} SHA256_CTX;

int SHA256_Init(SHA256_CTX *ctx);
int SHA256_Update(SHA256_CTX *ctx, const void *data, size_t bytes);
int SHA256_Final(unsigned char out[32], SHA256_CTX *ctx);
unsigned char *SHA256(const unsigned char *data, size_t bytes, unsigned char *out);

#endif
'''

# Android.mk's flags, plus two that are about this toolchain rather than the
# program: musl-gcc's GCC warns about a format-truncation the AOSP clang build
# does not (TestFileInit.h copies a 128-byte name into a 64-byte buffer, on
# purpose -- report_node is only ever a dm-N node name), and -Werror is kept.
CROSS_FLAGS = [
    '-std=gnu11', '-O2', '-Wall', '-Wextra', '-Werror',
    '-Wno-unused-function',
    # GCC 13 has format-truncation; the AOSP build's clang does not. The one
    # instance is snprintf(report_node, sizeof(report_node), "%s", reportnode)
    # where reportnode is the "/dev/block/dm-N" path -- shorter than 64 bytes by
    # construction, and the source is untouched.
    '-Wno-format-truncation',
    '-D_FILE_OFFSET_BITS=64',
    # The 8192-extent limit makes each mapping ~196 KiB; the arrays are moved off
    # PID 1's stack (TestFileInit.h/SystemStamp.h keep them in .bss), and these
    # two flags keep that true: any function frame over 128 KiB fails the build,
    # and every frame is recorded in stack-usage.txt as the evidence.
    '-fstack-usage', '-Wframe-larger-than=131072',
    '-static',
]


def sha256(path):
    digest = hashlib.sha256()
    with open(path, 'rb') as stream:
        for block in iter(lambda: stream.read(1 << 20), b''):
            digest.update(block)
    return digest.hexdigest()


def run(argv, cwd=None):
    """Run one build or check command, print it, and fail the build if it does.

    Nothing here hides a command: the transcript of the run in build.log is
    meant to be enough to repeat it by hand.
    """
    line = ' '.join(shlex.quote(str(a)) for a in argv)
    print('+ ' + line)
    result = subprocess.run([str(a) for a in argv], cwd=str(cwd) if cwd else None,
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result.stdout:
        text = result.stdout.rstrip('\n')
        if text:
            print(text)
        transcript.append('$ ' + line + '\n' + text + '\n')
    else:
        transcript.append('$ ' + line + '\n')
    if result.returncode != 0:
        sys.exit('command failed with exit code %d:\n  %s' % (result.returncode, line))
    return result.stdout


def output_of(argv):
    """Run a command whose text output is wanted rather than shown."""
    result = subprocess.run([str(a) for a in argv], text=True,
                            stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result.returncode != 0:
        sys.exit('command failed with exit code %d:\n  %s\n%s'
                 % (result.returncode, ' '.join(str(a) for a in argv), result.stdout))
    return result.stdout


def write_sha_header(include_dir):
    target = include_dir / 'openssl/sha.h'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(SHA_HEADER)
    return target


def host_sha_selftest(header_dir, build_dir):
    """Compile preinit-sha256.c for the host and run its NIST vectors."""
    compiler = shutil.which('gcc') or shutil.which('cc')
    if not compiler:
        sys.exit('no host C compiler to run the SHA-256 self-test with')
    binary = build_dir / 'preinit-sha256-selftest'
    run([compiler, '-std=gnu11', '-O2', '-Wall', '-Wextra', '-Werror',
         '-DPW3_PREINIT_SHA256_SELFTEST', '-I', header_dir, SHA_SOURCE, '-o', binary])
    run([binary])


def host_board_gate(board, other, header_dir, build_dir):
    """Run PreInit.c's release_is_this_board() for this board on the host.

    The function is `static`, so there is no way to call it from a second
    translation unit -- and it is in a file whose logic this build must not
    touch. The test is therefore one translation unit: PreInit.c is included
    with `main` renamed (it has exactly one main, in TestFileInit.h), and the
    test's own main calls the static function. Nothing in PreInit.c or its
    headers changes; the include order and the two defines are the AOSP ones.

    This is what `strings` cannot show: with -DPW3_BOARD_NAME the release
    string is built at run time ("-%s-android81"), so a binary can carry the
    right board name and still gate wrongly. The test checks the gate itself.
    """
    compiler = shutil.which('gcc') or shutil.which('cc')
    if not compiler:
        sys.exit('no host C compiler to run the board-gate test with')
    source = build_dir / ('board-gate-%s.c' % board)
    binary = build_dir / ('board-gate-%s' % board)
    source.write_text('''\
/* Generated by tools/build-preinit.py: calls PreInit.c's release_is_this_board()
 * for board "%(board)s" without changing the source under test. */
#define _GNU_SOURCE
#define _FILE_OFFSET_BITS 64
#define main pw3_testfile_init_main
#include "%(preinit)s"
#undef main
#include <stdio.h>
#include <string.h>

int main(void)
{
    const char *own = "3.0.35-lab126-" PW3_BOARD_NAME "-android81";
    const char *other = "3.0.35-lab126-%(other)s-android81";
    const char *own_long = "3.0.35-lab126-" PW3_BOARD_NAME "-android81 (builder@pw3-build)";
    int failed = 0;

    if (!release_is_this_board(own)) {
        printf("FAIL: released %%s refused for board %%s\\n", own, PW3_BOARD_NAME);
        failed = 1;
    }
    if (!release_is_this_board(own_long)) {
        printf("FAIL: longer banner %%s refused\\n", own_long);
        failed = 1;
    }
    if (release_is_this_board("3.0.35-lab126")) {
        printf("FAIL: a release with no board suffix accepted\\n");
        failed = 1;
    }
    if (release_is_this_board(other)) {
        printf("FAIL: the other model's release %%s accepted\\n", other);
        failed = 1;
    }
    if (!failed) {
        printf("board gate: ok for %%s (accepts %%s, refuses %%s)\\n",
               PW3_BOARD_NAME, own, other);
    }
    return failed;
}
''' % {'board': board, 'other': other, 'preinit': str(PREINIT / 'PreInit.c')})
    run([compiler, '-std=gnu11', '-O0', '-w', '-D_FILE_OFFSET_BITS=64',
         '-DPW3_BOARD_NAME="%s"' % board, '-I', header_dir, source, SHA_SOURCE, '-o', binary])
    run([binary])


def elf_facts(path, board):
    """The static-ARM shape, checked rather than assumed."""
    header = output_of(['readelf', '-h', path])
    segments = output_of(['readelf', '-l', path])
    class_ = re.search(r'^\s*Class:\s+(\S+)', header, re.M)
    type_ = re.search(r'^\s*Type:\s+(\S+)', header, re.M)
    machine = re.search(r'^\s*Machine:\s+(\S+)', header, re.M)
    flags = re.search(r'^\s*Flags:\s+(.+)$', header, re.M)
    entry = re.search(r'^\s*Entry point address:\s+(0x[0-9a-fA-F]+)', header, re.M)
    facts = {
        'class': class_.group(1) if class_ else None,
        'type': type_.group(1) if type_ else None,
        'machine': machine.group(1) if machine else None,
        'flags': flags.group(1).strip() if flags else None,
        'entry': entry.group(1) if entry else None,
        'has_interp': bool(re.search(r'^\s*INTERP\s', segments, re.M)),
        'exec_loads': [],
    }
    problems = []
    if facts['class'] != 'ELF32':
        problems.append('not ELF32: %r' % facts['class'])
    if facts['type'] != 'EXEC':
        problems.append('not an EXEC: %r' % facts['type'])
    if facts['machine'] != 'ARM':
        problems.append('not ARM: %r' % facts['machine'])
    if not facts['flags'] or 'Version5 EABI' not in facts['flags']:
        problems.append('not EABI5: %r' % facts['flags'])
    if facts['has_interp']:
        problems.append('has an INTERP segment: not statically linked')
    if not entry:
        problems.append('no entry point')
    for line in segments.splitlines():
        # "  LOAD  0x000000 0x00010000 0x00010000 0x14634 0x14634 R E 0x1000":
        # the permission field is one padded field ("R E"), not one token.
        parts = line.split()
        if len(parts) < 8 or parts[0] != 'LOAD':
            continue
        offset, vaddr, paddr, filesz, memsz = parts[1:6]
        perms = ''.join(parts[6:-1])
        align = parts[-1]
        if 'E' in perms:
            facts['exec_loads'].append({'offset': offset, 'vaddr': vaddr, 'filesz': filesz})
            if entry:
                start = int(vaddr, 16)
                end = start + int(filesz, 16)
                value = int(entry.group(1), 16)
                if not start <= value < end:
                    problems.append('entry point %s is outside the executable segment %s+%s'
                                    % (entry.group(1), vaddr, filesz))
    if not facts['exec_loads']:
        problems.append('no executable LOAD segment')
    facts['problems'] = problems
    return facts


def string_facts(path, board):
    """The contract string, and which shape the board gate took this compile."""
    text = output_of(['strings', '-a', path])
    facts = {
        'contract': CONTRACT in text,
        'board_literal': board in text,
        'board_suffix_folded': ('-%s-android81' % board) in text,
        'board_suffix_format': '-%s-android81' in text,
        'problems': [],
    }
    if not facts['contract']:
        facts['problems'].append('contract string %s is not in the binary' % CONTRACT)
    # Either the compiler folded "-%s-android81" with the board name into the
    # literal (as the AOSP clang build does: the release binary carries
    # "-pw3-android81"), or it kept the format and the name apart. Both gates
    # are the same one; host_board_gate() checks the behaviour either way.
    if not facts['board_suffix_folded'] and not (facts['board_suffix_format'] and facts['board_literal']):
        facts['problems'].append(
            'neither "-%s-android81" nor the "-%%s-android81" + "%s" pair is in the binary'
            % (board, board))
    return facts


def strip_binary(path, output):
    """A stripped copy, the way a release binary ships; the unstripped one is kept."""
    strip = shutil.which('arm-linux-gnueabi-strip') or shutil.which('strip')
    if not strip:
        sys.exit('no strip tool for the ARM binary')
    shutil.copyfile(path, output)
    run([strip, '--strip-all', output])
    return output


def stack_usage(build_dir, output_dir, board):
    """The per-function frame sizes GCC recorded, and the largest one.

    -fstack-usage writes one .su file per compiled source (in build_dir); the
    biggest frame is what would have to fit on PID 1's stack.
    """
    lines = []
    for path in sorted(build_dir.glob('*.su')):
        lines.extend(path.read_text().splitlines())
    frames = []
    for line in lines:
        parts = line.split('\t')
        if len(parts) >= 2 and parts[1].isdigit():
            frames.append((int(parts[1]), parts[0]))
    if not frames:
        sys.exit('no stack-usage output from the %s build' % board)
    frames.sort(reverse=True)
    (output_dir / ('stack-usage.%s.txt' % board)).write_text('\n'.join(lines) + '\n')
    largest = frames[0][0]
    if largest > 131072:
        sys.exit('the %s build has a %d-byte stack frame' % (board, largest))
    return {'largest_frame_bytes': largest,
            'largest_frame': frames[0][1],
            'top_frames': [{'bytes': b, 'function': f} for b, f in frames[:5]]}


def build_one(board, output_dir, include_dir, build_dir, musl, kernel_headers):
    binary = output_dir / ('pw3-testfile-init.%s' % board)
    objects = []
    for source in (PREINIT / 'PreInit.c', SHA_SOURCE):
        obj = build_dir / (source.stem + '.o')
        run([musl, *CROSS_FLAGS, '-DPW3_BOARD_NAME="%s"' % board,
             '-I', include_dir, '-idirafter', kernel_headers,
             '-c', source, '-o', obj], cwd=build_dir)
        objects.append(obj)
    run([musl, '-static', '-o', binary, *objects])
    usage = stack_usage(build_dir, output_dir, board)
    elf = elf_facts(binary, board)
    strings = string_facts(binary, board)
    problems = elf['problems'] + strings['problems']
    if problems:
        sys.exit('the %s build is not acceptable:\n  %s' % (board, '\n  '.join(problems)))
    stripped = strip_binary(binary, output_dir / ('pw3-testfile-init.%s.stripped' % board))
    return {
        'board': board,
        'compile': ' '.join(shlex.quote(str(a)) for a in
                            [musl, *CROSS_FLAGS, '-DPW3_BOARD_NAME="%s"' % board,
                             '-I', include_dir, '-idirafter', kernel_headers,
                             PREINIT / 'PreInit.c', SHA_SOURCE, '-o', binary]),
        'stack_usage': usage,
        'binary': {'name': binary.name, 'bytes': binary.stat().st_size, 'sha256': sha256(binary)},
        'stripped': {'name': stripped.name, 'bytes': stripped.stat().st_size,
                     'sha256': sha256(stripped)},
        'elf': elf,
        'strings': strings,
    }


def main():
    argument = argparse.ArgumentParser(description=__doc__,
                                       formatter_class=argparse.RawDescriptionHelpFormatter)
    argument.add_argument('--output', type=Path, required=True,
                          help='where the binaries and preinit-build.json are written')
    argument.add_argument('--board', action='append', default=None,
                          help='board name to pass as PW3_BOARD_NAME; repeatable, default voyage')
    argument.add_argument('--musl-gcc', type=Path, default=DEFAULT_MUSL,
                          help='musl-gcc wrapper (default: %(default)s)')
    argument.add_argument('--kernel-headers', type=Path, default=DEFAULT_KERNEL_HEADERS,
                          help='ARM kernel headers, added with -idirafter (default: %(default)s)')
    a = argument.parse_args()

    if platform.node() != (os.environ.get('READOM_BUILD_HOST') or 'lima-pw3') or os.geteuid() == 0:
        sys.exit('Run as builder in the build VM (hostname READOM_BUILD_HOST, default lima-pw3).')
    boards = a.board or ['voyage']
    for board in boards:
        if not re.fullmatch(r'[a-z][a-z0-9-]*', board):
            sys.exit('--board is a board name: lower-case letters, digits and "-"')
    for tool in (a.musl_gcc, PREINIT / 'PreInit.c', SHA_SOURCE):
        if not Path(tool).exists():
            sys.exit('%s is not there' % tool)
    if not a.kernel_headers.is_dir():
        sys.exit('%s (the ARM kernel headers) is not there; install linux-libc-dev-armel-cross'
                 % a.kernel_headers)

    global transcript
    transcript = []
    a.output.mkdir(parents=True, exist_ok=True)
    include_dir = a.output / 'include'
    include_dir.mkdir(exist_ok=True)
    write_sha_header(include_dir)

    with tempfile.TemporaryDirectory(prefix='preinit-build-') as temporary:
        build_dir = Path(temporary)
        host_sha_selftest(include_dir, build_dir)
        other = {'voyage': 'pw3', 'pw3': 'voyage'}
        for board in boards:
            host_board_gate(board, other.get(board, 'pw3'), include_dir, build_dir)
        built = [build_one(board, a.output, include_dir, build_dir,
                           str(a.musl_gcc), str(a.kernel_headers)) for board in boards]

    facts = {
        'schema': 1,
        'contract': CONTRACT,
        'compile_flags': CROSS_FLAGS,
        'musl_gcc': str(a.musl_gcc),
        'musl_version': output_of([str(a.musl_gcc), '--version']).splitlines()[0],
        'kernel_headers': str(a.kernel_headers),
        'source': {
            'PreInit.c': sha256(PREINIT / 'PreInit.c'),
            'preinit-sha256.c': sha256(SHA_SOURCE),
        },
        'built': built,
    }
    (a.output / 'preinit-build.json').write_text(json.dumps(facts, indent=2) + '\n')
    (a.output / 'build.log').write_text('\n'.join(transcript))
    for item in built:
        print('%-7s %8d B  sha256 %s  (stripped %d B, sha256 %s)'
              % (item['board'], item['binary']['bytes'], item['binary']['sha256'],
                 item['stripped']['bytes'], item['stripped']['sha256']))
    print('Wrote %s' % (a.output / 'preinit-build.json'))


if __name__ == '__main__':
    main()
